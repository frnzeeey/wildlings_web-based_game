import Phaser from 'phaser';

interface PartBox {
  x: number;
  y: number;
  w: number;
  h: number;
  scale?: number; // raster scale when it differs from manifest.scale (background layers)
}

export interface BgLayer {
  key: string;
  factor: number;
  x: number;
  y: number;
}

/** Per-species rig anchors written by tools/gen-art.mjs (every critter has its own body plan). */
export interface SpeciesRig {
  eyes: { x: number; y: number; r: number; far: boolean }[];
  mouth: { x: number; y: number };
  feet: [number, number][];
  arm: { x: number; y: number };
  top: number;
  tail: boolean;
  team: 'back' | 'body' | 'head';
}

interface Manifest {
  scale: number;
  parts: Record<string, PartBox>;
  species: Record<string, SpeciesRig>;
  backgrounds: Record<string, BgLayer[]>;
}

/**
 * Shared SVG art (generated by tools/gen-art.mjs). Each part has a local origin; images are
 * rasterised at `scale`x and drawn at 1/scale so they stay crisp when the camera zooms in.
 */
class Art {
  manifest: Manifest = { scale: 3, parts: {}, species: {}, backgrounds: {} };

  get scale(): number {
    return 1 / this.manifest.scale;
  }

  async loadManifest(): Promise<void> {
    const res = await fetch('art/manifest.json');
    this.manifest = await res.json();
  }

  /** Everything except background layers, which load per map (see preloadMap). */
  preload(load: Phaser.Loader.LoaderPlugin): void {
    for (const key of Object.keys(this.manifest.parts)) if (!key.startsWith('bg_')) this.queue(load, key);
  }

  preloadMap(load: Phaser.Loader.LoaderPlugin, textures: Phaser.Textures.TextureManager, mapId: string): void {
    for (const l of this.manifest.backgrounds[mapId] ?? []) if (!textures.exists(l.key)) this.queue(load, l.key);
  }

  private queue(load: Phaser.Loader.LoaderPlugin, key: string): void {
    const b = this.manifest.parts[key];
    const s = b.scale ?? this.manifest.scale;
    load.svg(key, `art/${key}.svg`, { width: Math.round(b.w * s), height: Math.round(b.h * s) });
  }

  /** Display scale for a part (1 / its raster scale). */
  partScale(key: string): number {
    return 1 / (this.manifest.parts[key]?.scale ?? this.manifest.scale);
  }

  has(key: string): boolean {
    return key in this.manifest.parts;
  }

  species(id: string) {
    return this.manifest.species[id] ?? Object.values(this.manifest.species)[0];
  }

  url(key: string): string {
    return `art/${key}.svg`;
  }

  applyOrigin(img: Phaser.GameObjects.Image, key: string): void {
    const b = this.manifest.parts[key];
    if (b) img.setOrigin(-b.x / b.w, -b.y / b.h);
  }

  image(scene: Phaser.Scene, key: string, x = 0, y = 0): Phaser.GameObjects.Image {
    const img = scene.add.image(x, y, key).setScale(this.partScale(key));
    this.applyOrigin(img, key);
    return img;
  }
}

export const art = new Art();
